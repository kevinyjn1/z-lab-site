/*
 * The Atombot mark as data, shared by the home page hero and the swarm sketch.
 *
 * ART is a small bitmap traced from the team's logo ('#' is ink, cells are square).
 * window.ZLabAtombot.cells lists the ink cells as [u, v, stroke, s]:
 *   u, v    cell center, measured from the middle of the bitmap in units of its width
 *   stroke  which of the three brush strokes the cell belongs to (0, 1, 2)
 *   s       how far along that stroke the cell sits: 0 at the thick head, 1 at the thin tail
 */
window.ZLabAtombot = (() => {
  "use strict";

  const ART = [
    "...........................#####............................",
    ".........................#########..........................",
    ".......................############.........................",
    ".......................#############........................",
    ".......................##############.......................",
    "......................################......................",
    "......................################......................",
    ".....................##################.....................",
    "....................####################....................",
    "....................####################....................",
    ".....................###.###############....................",
    "..............................###########...................",
    "...............................##########...................",
    ".................................#########..................",
    "..................................########..................",
    "..................................########..................",
    "...................................#######..................",
    "....................................######..................",
    "......................####...........######.................",
    "...................######............######.................",
    ".................#######..............#####.................",
    "................######................#####.................",
    "..............#######..................####.................",
    ".............#######....................###.................",
    "............#######.....................###.................",
    "...........#######......................###.................",
    "..........########.......................##.................",
    ".........########........................##.................",
    "........########.........................##.................",
    ".......#########.........................#..................",
    ".......#########............................................",
    "......#########..................................#..........",
    ".....##########..................................##.........",
    ".....#########...................................###........",
    "....##########...................................###........",
    "....##########..................................#####.......",
    "....##########.................................########.....",
    "...###########................................#########.....",
    "...###########.......##......................###########....",
    "...###########........###..................#############....",
    "...###########........######............################....",
    "...############.........################################....",
    "...############..........##############################.....",
    "....###########...........#############################.....",
    ".....###########............###########################.....",
    ".....#############............########################......",
    "......############..............#####################.......",
    ".........#.####....................################.........",
    "........................................########............",
  ];

  const rows = ART.length;
  const cols = ART[0].length;
  const span = Math.max(cols, rows);
  const ink = (i, j) => j >= 0 && j < rows && i >= 0 && i < cols && ART[j][i] === "#";

  /* Flood fill the ink into connected blobs; the three largest are the brush strokes. */
  const blob = new Int16Array(cols * rows).fill(-1);
  const blobSize = [];
  for (let j = 0; j < rows; j++) {
    for (let i = 0; i < cols; i++) {
      if (!ink(i, j) || blob[j * cols + i] >= 0) continue;
      const id = blobSize.length;
      const stack = [[i, j]];
      blob[j * cols + i] = id;
      let count = 0;
      while (stack.length) {
        const [x, y] = stack.pop();
        count++;
        for (let dy = -1; dy <= 1; dy++) {
          for (let dx = -1; dx <= 1; dx++) {
            if (ink(x + dx, y + dy) && blob[(y + dy) * cols + x + dx] < 0) {
              blob[(y + dy) * cols + x + dx] = id;
              stack.push([x + dx, y + dy]);
            }
          }
        }
      }
      blobSize.push(count);
    }
  }
  const main = blobSize.map((_, id) => id).sort((a, b) => blobSize[b] - blobSize[a]).slice(0, 3);

  const cells = [];
  for (let j = 0; j < rows; j++) {
    for (let i = 0; i < cols; i++) {
      if (ink(i, j)) cells.push([(i + 0.5 - cols / 2) / span, (j + 0.5 - rows / 2) / span, main.indexOf(blob[j * cols + i]), 0]);
    }
  }
  /* A stray speck of ink joins whichever stroke is closest. */
  const inStroke = cells.filter((c) => c[2] >= 0);
  cells.forEach((c) => {
    if (c[2] >= 0) return;
    let best = Infinity;
    inStroke.forEach((o) => {
      const d = (o[0] - c[0]) ** 2 + (o[1] - c[1]) ** 2;
      if (d < best) {
        best = d;
        c[2] = o[2];
      }
    });
  });

  /* The strokes curl around the middle of the mark, so the angle around it orders each one. */
  const mx = cells.reduce((a, c) => a + c[0], 0) / cells.length;
  const my = cells.reduce((a, c) => a + c[1], 0) / cells.length;
  for (let k = 0; k < 3; k++) {
    const own = cells.filter((c) => c[2] === k);
    const angle = own.map((c) => Math.atan2(c[1] - my, c[0] - mx));
    const mean = Math.atan2(angle.reduce((a, t) => a + Math.sin(t), 0), angle.reduce((a, t) => a + Math.cos(t), 0));
    const turn = angle.map((t) => Math.atan2(Math.sin(t - mean), Math.cos(t - mean)));
    const lo = Math.min(...turn);
    const hi = Math.max(...turn);
    own.forEach((c, n) => (c[3] = (turn[n] - lo) / (hi - lo)));
    /* the head is the thick end, which holds more ink */
    if (own.filter((c) => c[3] < 0.5).length < own.length / 2) own.forEach((c) => (c[3] = 1 - c[3]));
  }

  return { cells, cols, rows };
})();
